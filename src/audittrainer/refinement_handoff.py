def direct_binding(obs):
    result=obs['returned_child']['result'];a=result['artifact'];e=result['evidence']
    assert a is not None and result['functional_status']=='PASS' and e['status']=='PASS'
    assert result['node_id']==a['node_id']==e['binding']['artifact']['node_id']
    assert a['source_hash']==e['binding']['source_hash'] and a['version']==e['binding']['artifact']['version']
    assert e['evidence_id'] in [v['evidence_id'] for v in obs['visible_evidence']]
    return {'child_id':result['node_id'],'artifact_version':a['version'],'artifact_hash':a['source_hash'],'evidence_ids':[e['evidence_id']]}


def clarified_prompt(tokenizer,observation,**kwargs):
    obs=deepcopy(observation)
    if obs['phase']=='RESOLVE_CHILD' and obs.get('returned_child'):
        result=obs['returned_child']['result'];a=result.get('artifact');e=result.get('evidence')
        summary={'current_consumer':obs['node_id'],'returned_direct_child':result['node_id'],
                 'artifact':None if a is None else {k:a[k] for k in ['node_id','version','source_hash']},
                 'functional_status':result['functional_status'],
                 'evidence':None if e is None else {k:e[k] for k in ['evidence_id','status','target_ref']}}
        obs['root_spec']+='\nCurrent returned direct child (existing public fields): '+canonical(summary)+'\nResolve this direct child only. Select node, version, hash and evidence together from this returned artifact. Nested dependency bindings describe its dependencies, not the current returned child. If no artifact exists, do not consume a descendant instead.'
    return summary_prompt(tokenizer,obs,**kwargs)


def prepare():
    ROOT.mkdir(parents=True,exist_ok=True)
    if (ROOT/'request.json').exists():return
    source=Path('runs/refinement/internal_probe');prior=json.loads((source/'request.json').read_text());selection=[]
    for s in prior['selection']:
        for rep in range(4):
            path=source/s['root_id']/'SPLIT'/f'repeat_{rep:02d}'
            checks=json.loads((path/'execution_checks.json').read_text())
            eligible=any(v['visibility']=='PRIVATE' and v['status']=='PASS' for v in checks['local'])
            selection.append({'root_id':s['root_id'],'rep':rep,'source':str(path),'qualified':eligible})
    assert sum(s['qualified'] for s in selection)==5
    guarded_json(ROOT/'request.json',{'selection':selection,'framework':prior['framework'],'config':prior['config'],
        'adapters':prior['adapters'],'hashes':prior['hashes'],'seed':411000713,
        'manual_cases':8,'autonomous_cases':10,'updates':0,
        'manual':'5 qualified artifacts: replay unchanged prefix, correct complete direct-child consume binding only. 3 missing artifacts: separately replace rejected prepare write with minimal forwarding wrapper, then correct complete root consume binding. New suffix generated by frozen executor; manual cases are causal diagnostics, not model scores.',
        'autonomous':'5 qualified fixed states x ORIGINAL/CLARIFIED. Replay unchanged prefix; frozen model autonomously selects all consume fields and writes root code. Clarification only projects current public direct-child fields. One paired fresh seed per source state; retries and failures retained.'})
    guarded_json(ROOT/'gpu_resources.json',{'devices':['0','1','2'],'min_free_mib':{'collect':16000}})


class Replay:
    def __init__(self,policy,executor,selected,condition):
        self.policy,self.executor=policy,executor
        self.condition=condition;self.selected=selected;self.cursor=0;self.interventions=[]
        events=read_jsonl(Path(selected['source'])/'runtime/trace.jsonl')
        self.events=[e for e in events if e['event_kind']=='POLICY' and e['observation_before']['phase'] in {'NEW','IMPLEMENT','RESOLVE_CHILD'}]
        if selected['qualified']:
            self.boundary=next(i for i,e in enumerate(self.events) if e['node_id']=='N0' and e['observation_before']['phase']=='RESOLVE_CHILD')
        else:
            self.boundary=next(i for i,e in enumerate(self.events) if e['node_id']=='N0_p1_prepare' and e['host_result']['code']=='INTERFACE_MISMATCH')
        self.code_fixed=False;self.binding_fixed=False

    def act(self,obs):
        if self.cursor<self.boundary:
            e=self.events[self.cursor];self.cursor+=1
            assert (obs['node_id'],obs['phase'],obs['incoming_contract'])==(e['node_id'],e['observation_before']['phase'],e['observation_before']['incoming_contract'])
            return PolicyOutput(raw_text=e['raw_output'],token_usage=TokenUsage(**e['usage']),model_identity=e['model_identity'],
                model_input=e.get('model_input'),output_token_ids=e.get('output_token_ids',[]),generation_truncated=e.get('generation_truncated',False))
        if self.cursor==self.boundary:
            e=self.events[self.boundary]
            assert obs['node_id']==e['node_id'] and obs['phase']==e['observation_before']['phase']
            if self.selected['qualified']:
                assert direct_binding(obs)==direct_binding(e['observation_before'])
                assert obs['returned_child']['source']==e['observation_before']['returned_child']['source']
            self.cursor+=1
        if self.condition=='MANUAL' and not self.selected['qualified'] and not self.code_fixed:
            assert obs['node_id']=='N0_p1_prepare' and obs['phase']=='IMPLEMENT'
            old=self.events[self.boundary]['parsed_action'];action=deepcopy(old)
            deps=obs['approved_dependencies'];assert len(deps)==1
            d=deps[0];assert obs['incoming_contract']['signature']['name']=='prepare'
            action['args']['source']=f"from nodes.{d['child_id']} import prepare as {d['alias']}\n\ndef prepare(items):\n    return {d['alias']}(items)\n"
            action['args']['declared_dependencies']=deps
            self.code_fixed=True
            return self.manual(obs,old,action,'current_prepare_interface_and_scope')
        if self.condition=='MANUAL' and obs['node_id']=='N0' and obs['phase']=='RESOLVE_CHILD' and not self.binding_fixed:
            old=next(e['parsed_action'] for e in self.events if e['node_id']=='N0' and e['observation_before']['phase']=='RESOLVE_CHILD' and (e.get('parsed_action') or {}).get('action')=='consume')
            action=deepcopy(old);action['args'].update(direct_binding(obs));assert not action['args']['accept_unverified']
            self.binding_fixed=True
            return self.manual(obs,old,action,'complete_direct_child_binding')
        return self.policy.act(obs) if obs['phase']=='NEW' else self.executor.act(obs)

    def manual(self,obs,old,action,kind):
        self.interventions.append({'kind':kind,'node':obs['node_id'],'before':old,'after':action})
        return PolicyOutput(raw_text=canonical(action),token_usage=TokenUsage(),model_identity={'backend':'MANUAL_CAUSAL_INTERVENTION','kind':kind})


def run(condition):
    r=json.loads((ROOT/'request.json').read_text());_,policy,executor,rows,tests=context('AFTER');before=fingerprints(policy)
    executor.llm.prompt_builder=clarified_prompt if condition=='CLARIFIED' else summary_prompt
    results=[]
    for index,s in enumerate(r['selection']):
        if condition!='MANUAL' and not s['qualified']:continue
        replay=Replay(policy,executor,s,condition)
        planner=SimpleNamespace(act=replay.act,cost=policy.cost,identity=policy.identity)
        execution=SimpleNamespace(act=replay.act,cost=executor.cost,llm=executor.llm)
        directory=ROOT/condition/s['root_id']/f"repeat_{s['rep']:02d}"
        c=run_case(rows[s['root_id']],tests,r['framework'],r['config'],planner,execution,directory,r['seed']+index)
        assert c['status']=='COMPLETE' and replay.cursor>replay.boundary
        assert condition!='MANUAL' or replay.binding_fixed
        checks=local_checks(c,rows[s['root_id']],tests,r['framework'])
        write_json(directory/'interventions.json',replay.interventions);write_json(directory/'execution_checks.json',checks)
        # Existing accepted code is preserved in qualified-artifact controls.
        original=Path(s['source'])/'runtime/artifacts';preserved=[]
        for p in original.glob('*/*.py'):
            q=directory/'runtime/artifacts'/p.relative_to(original)
            if s['qualified'] or p.parent.name!='N0_p1_prepare':
                assert q.exists() and file_hash(p)==file_hash(q)
                preserved.append(str(p.relative_to(original)))
        results.append({'selection':s,'case':c,'checks':checks,'preserved_code':preserved,'interventions':replay.interventions})
    assert fingerprints(policy)==before
    write_json(ROOT/condition/'result.json',{'status':'COMPLETE','condition':condition,'frozen':before,'results':results})


def report():
    r=json.loads((ROOT/'request.json').read_text());groups={c:json.loads((ROOT/c/'result.json').read_text()) for c in ['MANUAL','ORIGINAL','CLARIFIED']}
    assert all(v['frozen']==groups['MANUAL']['frozen'] for v in groups.values())
    assert all(file_hash(Path(p)/'adapter_model.safetensors')==r['hashes'][k] for k,p in r['adapters'].items())
    summary=[]
    for cond,g in groups.items():
        for qualified in [True,False]:
            cs=[x for x in g['results'] if x['selection']['qualified']==qualified]
            if not cs:continue
            binding_success=0
            for c in cs:
                events=read_jsonl(Path(c['case']['run_dir'])/'runtime/trace.jsonl')
                binding_success+=any(e['node_id']=='N0' and e['host_result']['code']=='CHILD_CONSUMED'
                    and e['host_result']['details']['consumption']['child_node']=='N0_p1_prepare' for e in events)
            summary.append({'condition':cond,'qualified_at_start':qualified,'n':len(cs),'root_success':sum(c['case']['reward']['y'] for c in cs),
                'direct_prepare_consumed':binding_success,
                'local_private_pass':sum(any(v['visibility']=='PRIVATE' and v['status']=='PASS' for v in c['checks']['local']) for c in cs),
                'parent_called':sum(any(d['child_id']=='N0_p1_prepare' and d.get('called') for d in c['checks'].get('dependency_usage',[])) for c in cs)})
    out={'status':'COMPLETE','summary':summary,'groups':groups};write_json(ROOT/'result.json',out);print(json.dumps(summary))

